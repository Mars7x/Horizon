#!/usr/bin/env python3
"""Generate Horizon's offline hash catalog from the pinned upstream DAT."""
import hashlib
import shlex
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

REVISION = "9a899f5b13ed1c355491e342203be29bc573323b"
# Verified before parsing; updates require reviewing a new upstream snapshot.
SOURCE_SHA256 = "0b8bd3a414276e9c31137b0a245fcdaf917d34fd035e02499c965a290ac8fce4"
SOURCE_URL = (
    f"https://raw.githubusercontent.com/libretro/libretro-database/{REVISION}/"
    "metadat/no-intro/Nintendo%20-%20Game%20Boy%20Advance.dat"
)


def generate(source: bytes) -> str:
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("input differs from the reviewed upstream snapshot")
    entries = set()
    title = None
    for line in source.decode("utf-8").splitlines():
        line = line.strip()
        if line == "game (":
            title = None
        elif line.startswith("name "):
            title = shlex.split(line)[1]
        elif line.startswith("rom ("):
            fields = shlex.split(line[5:-1])
            if len(fields) % 2:
                raise ValueError("invalid ROM attributes")
            rom = dict(zip(fields[::2], fields[1::2]))
            sha1, size = rom["sha1"].lower(), int(rom["size"])
            if not title or len(sha1) != 40 or any(c not in "0123456789abcdef" for c in sha1):
                raise ValueError("invalid title or SHA-1")
            entries.add((sha1, size, title))
    if not entries:
        raise ValueError("empty catalog")
    output = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- SPDX-FileCopyrightText: No-Intro and Libretro database contributors -->',
        '<!-- SPDX-License-Identifier: CC-BY-SA-4.0 -->',
        f'<!-- Derived from {escape(SOURCE_URL)}; generated by scripts/generate-gba-catalog.py. -->',
        '<datafile>',
        f'<header><name>Nintendo - Game Boy Advance (No-Intro/libretro {REVISION})</name></header>',
    ]
    for sha1, size, title in sorted(entries):
        output.append(f'<game name={quoteattr(title)}><rom size="{size}" sha1="{sha1}"/></game>')
    output.append('</datafile>')
    return "\n".join(output) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate-gba-catalog.py UPSTREAM.dat OUTPUT.xml")
    Path(sys.argv[2]).write_text(generate(Path(sys.argv[1]).read_bytes()), encoding="utf-8")
