#!/usr/bin/env python3
"""Generate Horizon's offline hash catalogs from pinned upstream DATs."""
import hashlib
import shlex
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

REVISION = "9a899f5b13ed1c355491e342203be29bc573323b"
# Each input is verified before parsing; updates require reviewing a new
# upstream snapshot. Keys are the catalog names in data/catalogs.
SYSTEMS = {
    "gba": (
        "Nintendo - Game Boy Advance",
        "0b8bd3a414276e9c31137b0a245fcdaf917d34fd035e02499c965a290ac8fce4",
    ),
    "gb": (
        "Nintendo - Game Boy",
        "2dc0e5dd0ec696b60a4fc1987b1f84814a08cebc31138551f2e7ef9f11e10f74",
    ),
    "gbc": (
        "Nintendo - Game Boy Color",
        "63cd203e8bc36273f13129be0b039c023f8475e5c82e69776bf659534041fb5a",
    ),
}


def source_url(name: str) -> str:
    return (
        f"https://raw.githubusercontent.com/libretro/libretro-database/{REVISION}/"
        f"metadat/no-intro/{name.replace(' ', '%20')}.dat"
    )


def generate(system: str, source: bytes) -> str:
    name, digest = SYSTEMS[system]
    if hashlib.sha256(source).hexdigest() != digest:
        raise ValueError("input differs from the reviewed upstream snapshot")
    entries = set()
    title = None
    for line in source.decode("utf-8").splitlines():
        line = line.strip()
        if line == "game (":
            title = None
        elif line.startswith("name "):
            title = shlex.split(line)[1]
        elif line.startswith("rom ("):
            fields = shlex.split(line[5:-1])
            if len(fields) % 2:
                raise ValueError("invalid ROM attributes")
            rom = dict(zip(fields[::2], fields[1::2]))
            sha1, size = rom["sha1"].lower(), int(rom["size"])
            if not title or len(sha1) != 40 or any(c not in "0123456789abcdef" for c in sha1):
                raise ValueError("invalid title or SHA-1")
            entries.add((sha1, size, title))
    if not entries:
        raise ValueError("empty catalog")
    output = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- SPDX-FileCopyrightText: No-Intro and Libretro database contributors -->',
        '<!-- SPDX-License-Identifier: CC-BY-SA-4.0 -->',
        f'<!-- Derived from {escape(source_url(name))}; generated by scripts/generate-hash-catalog.py. -->',
        '<datafile>',
        f'<header><name>{escape(name)} (No-Intro/libretro {REVISION})</name></header>',
    ]
    for sha1, size, title in sorted(entries):
        output.append(f'<game name={quoteattr(title)}><rom size="{size}" sha1="{sha1}"/></game>')
    output.append('</datafile>')
    return "\n".join(output) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 4 or sys.argv[1] not in SYSTEMS:
        raise SystemExit(
            f"usage: generate-hash-catalog.py {{{','.join(SYSTEMS)}}} UPSTREAM.dat OUTPUT.xml"
        )
    output = generate(sys.argv[1], Path(sys.argv[2]).read_bytes())
    Path(sys.argv[3]).write_text(output, encoding="utf-8")
